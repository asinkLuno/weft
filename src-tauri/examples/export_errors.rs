#[path = "../src/weft/errors.rs"]
#[allow(dead_code)]
mod errors;

use std::{fs, path::Path};
use ts_rs::{Config, TS};

fn main() {
    let output = Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/generated/validation-error.ts");
    fs::create_dir_all(output.parent().expect("generated directory"))
        .expect("create generated directory");
    let cfg = Config::default();
    let header = "// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.\n\n";
    let span = format!("export {}\n\n", errors::SourceSpan::decl(&cfg));
    let validation = format!("export {}\n", errors::ValidationError::decl(&cfg));
    fs::write(output, format!("{header}{span}{validation}")).expect("write validation error type");
}
